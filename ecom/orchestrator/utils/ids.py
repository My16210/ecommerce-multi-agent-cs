"""订单号的形状——**全仓库唯一的一份定义**。

为什么单独开一个模块只放一个正则
--------------------------------
因为"两处各写一遍"这件事在这个项目里**真的出过事故**：

换真实数据时，`workers/order.py` 那边把位数门槛从 6 位放宽到了 5 位，
`core/router.py` 里的那份没跟着改。**这个分叉不报任何错**——DataCo 的订单号
最大 77204（5 位），所以路由里那条 6 位规则对真实订单一笔都命中不了，
同时又会把发票号、日期串这种 6 位以上的数字路由成"查订单"。更要命的是
两处各自看都"对"：路由认得出的订单号，抽取层认不出。

当时是在两边都写了「必须和对方一模一样」的注释来兜的。注释挡不住漂移，
**少一个可以分叉的地方才挡得住**。所以改成只有一个定义。

为什么放 `utils/` 而不是 `tools/order_tools.py`
-----------------------------------------------
`order_tools.py` 语义上更像归属地，但它是 `from ecom.orchestrator.db.engine
import ...` 的。常量放那里，`core/router.py` 就会变成
`core → tools → db.engine` 的反向依赖，把 core 层拖进数据库。

`utils/` 是叶子包，`core/router.py` 和 `workers/order.py` **本来就已经**
import 了它下面的 `json_utils` / `llm` / `logger` / `tokens`，所以放这里
不引入任何新的层依赖。
"""
import re

# 订单号：5 位以上纯数字。
#
# 【为什么是 5 位起步】DataCo 的 Order Id 实测是 1~5 位（最小 1，最大 77204，不补零）。
# 门槛只能取"最长的那个量级"——放宽到 4 位会让「2025 年买的」里的 2025 被判成
# 订单号，那比认不出短订单号更糟。所以 1~4 位的订单号在对话里**认不出来**，
# 这是一条已知边界（写在 README 的"明确不做"里），不是在正则里偷偷补零绕过去。
#
# 【为什么是 (?<!\w) 而不是 (?<!\d)】客户号是 C20755 这个形状。如果只挡"前面是
# 数字"，`C20755` 里那串 20755 会被当成订单号——一句话里同时提到客户号和订单号时，
# 认出来的会是客户号。挡"前面是字母或数字"才分得开。
#
# 用法两处，含义不同，所以**不要**试图把它包装成一个"提取订单号"的函数：
#   · core/router.py           -> .search()   只关心"像不像订单号"，用来选 worker
#   · workers/order.py         -> .search()   挑出要查的那一笔
#                              -> .fullmatch() 校验模型吐回来的字段形状对不对
ORDER_ID_RE = re.compile(r"(?<!\w)(\d{5,})(?!\d)")
