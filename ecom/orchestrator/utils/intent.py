"""
一句话里的"意图"判断。目前只有一条：**用户是不是在明确要求人工客服**。

【为什么不做成模型判断】
「转人工」是一个**动作**，不是一个需要理解的问题。把它交给模型，会多一次
调用、多一个失败点，而且模型有可能"觉得还能答"就继续答——用户已经明确
要求了，这不是模型该替他决定的事。规则命中就直接转，规则没命中再走图。

【为什么规则要写得这么窄】
中文里「人工」两个字本身不表示任何诉求：**「退货需要人工审核吗」**是政策
咨询，「人工客服」才是转人工。只按「人工」两个字匹配，会把一半的售后政策
问题误判成转人工——而这类误判的表现是"问政策，系统说已为你转接人工"，
比答不上来更难解释。所以这里只认三种完整说法：
  · 转人工 / 转真人（可能带「帮我/麻烦」前缀）
  · 人工客服 / 真人客服 / 人工服务 / 人工坐席 / 人工专员
  · 找、要、叫、请、联系、接 + 人工/真人，且后面跟标点或句尾
单独一个「人工」也算：用户在对话框里打这两个字，意图没有第二种解释。
"""
import re

# 全角/半角空白都去掉再匹配：“转 人 工”这种打字习惯不该改变判断。
_HUMAN_PATTERNS = (
    re.compile(r"转\s*(?:人工|真人)"),
    re.compile(r"(?:人工|真人)\s*(?:客服|服务|坐席|专员)"),
    re.compile(r"(?:找|要|叫|请|联系|接)\s*(?:人工|真人)(?:[!！。.？?，,~～]|$)"),
    re.compile(r"^(?:人工|真人)(?:客服)?[!！。.？?，,~～]*$"),
)


def wants_human(question: str) -> bool:
    """这句话是不是在要求人工客服。命中只代表"该转"，不代表"该跳过安全规则"。"""
    text = "".join(str(question or "").split())
    if not text:
        return False
    return any(pattern.search(text) for pattern in _HUMAN_PATTERNS)
