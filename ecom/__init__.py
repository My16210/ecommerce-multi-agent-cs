"""
电商智能客服：一个项目，三个子系统。

    ecom.orchestrator   Supervisor + Worker 编排（路由 / 汇总 / 决策）
    ecom.knowledge      知识库（混合检索 + rerank + 生成 + 人审 + 评测）
    ecom.analytics      数据分析（写 pandas 代码 → 沙箱执行 → 审查 → 纠错）

【为什么三个子系统装在一个 `ecom` 里，而不是三个并列的顶层包】

它们原本是三个独立仓库，各自有一个顶层包叫 `src`（还有两个叫 `config`）。
同一进程里两个 `src` 必然有一个静默解析错——不报错，只是 `from src.x import y`
拿到另一个仓库的模块。当时是用**进程边界**绕开的：知识库走进程内、数据分析走
子进程，整套设计都在迁就这件事。

合并之后不必再绕：顶层包名就是全局命名空间，**一个 `ecom` 从构造上撞不了**。
所以原先为绕开撞名而写的那几处代码（`sys.path` 挂载、防撞名运行时闸门、
"不许占用 sibling 的包名"的测试）全部作废——这正是合并该换来的东西。

数据分析 worker **仍然走子进程**，但理由变了，见 orchestrator/workers/analytics.py：
不再是命名逼的，而是它要执行模型生成的代码，需要一个能真杀死的边界。
"""
